import express from 'express';
import { fileURLToPath } from 'node:url';
import { ServerGameSession } from '../game.js';
import { botRequest } from './protocol.js';

// Explicit public teaching files only. Never serve the repository or uploads.
export function createBotLearningRouter() {
  const router = express.Router();
  const files = [
    ['main.py', '../../examples/bots/starter.py'],
    ['first_legal.py', '../../examples/bots/first_legal.py'],
    ['goal_seeker.py', '../../examples/bots/goal_seeker.py'],
    ['bot-api-v1.md', '../../docs/bot-api-v1.md']
  ];
  for (const [name, relative] of files) {
    router.get(`/${name}`, (_req, res) => res.download(fileURLToPath(new URL(relative, import.meta.url)), name));
  }
  router.get('/request.json', (_req, res) => {
    // Demonstration generated by the same engine as real matches; never persisted.
    const game = new ServerGameSession('learning-example');
    res.attachment('request.json').json(botRequest(game, 'P1', 0));
  });
  return router;
}
